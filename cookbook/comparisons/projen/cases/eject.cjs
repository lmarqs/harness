'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { measure, write, read } = require('../lib/measure.cjs');
const { execute } = require('./packaging.cjs');

function eject(root, edit) {
  const rc = [
    "const {javascript,LogLevel} = require('projen');",
    "const p = new javascript.NodeProject({name:'probe-eject',outdir:__dirname,",
    "defaultReleaseBranch:'main',packageManager:javascript.NodePackageManager.NPM,",
    "github:false,release:false,depsUpgrade:false,licensed:false,minNodeVersion:'22.0.0',",
    "logging:{level:LogLevel.OFF}});",
    "p.package.addField('customConfig',{value:'keep'});",
    "p.synth();",
  ].join('\n');
  write(root, '.projenrc.js', rc);
  const env = {
    NODE_PATH: path.dirname(path.dirname(require.resolve('projen/package.json'))),
    PROJEN_DISABLE_POST: 'true', DEBUG: 'false',
  };
  execute([path.join(root, '.projenrc.js')], root, env);
  if (edit) write(root, '.gitignore', read(root, '.gitignore') + 'manual-after-synth/\n');
  const before = read(root, '.gitignore');
  const cli = require.resolve('projen/bin/projen');
  execute([cli, '--no-post', 'eject'], root, env);
  const after = read(root, '.gitignore');
  const pkg = JSON.parse(read(root, 'package.json'));
  return {
    before, after, package: pkg,
    rc_backed_up: fs.existsSync(path.join(root, '.projenrc.js.bak')),
    ownership_manifest_exists: fs.existsSync(path.join(root, '.projen/files.json')),
    writable: Boolean(fs.statSync(path.join(root, '.gitignore')).mode & 0o200),
    standalone_task_runner: fs.existsSync(path.join(root, 'scripts/run-task.cjs')),
    tasks_metadata_remains: fs.existsSync(path.join(root, '.projen/tasks.json')),
  };
}
function ejectCases() {
  return [
    measure('native-eject', 'native-cli', 'Keep generated native configuration and release projen management', root => {
      const result = eject(root, false);
      return { satisfies: !result.after.includes('Generated by projen') && result.rc_backed_up && !result.ownership_manifest_exists && result.writable && !result.package.devDependencies?.projen && result.package.customConfig.value === 'keep', observed: 'Actual projen --no-post eject removes markers and its dependency, makes files writable and backs up the RC file. Native task-runner artifacts remain.', ...result };
    }),
    measure('native-eject-preserves-manual-edits', 'native-cli', 'Eject retains manual additions to generated files', root => {
      const result = eject(root, true);
      return { satisfies: result.after.includes('manual-after-synth/'), observed: 'Eject runs synthesis; a manual addition to the generated ignore file is overwritten.', ...result };
    }),
  ];
}
module.exports = { ejectCases };
